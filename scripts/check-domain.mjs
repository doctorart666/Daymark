import ts from 'typescript';
import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const compile=p=>ts.transpileModule(readFileSync(p,'utf8'),{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022}}).outputText;
const modelsUrl='data:text/javascript;base64,'+Buffer.from(compile('lib/models.ts')).toString('base64');
const models=await import(modelsUrl);
const reminderSource=compile('lib/reminders.ts').replace("'./models'",JSON.stringify(modelsUrl));
const reminders=await import('data:text/javascript;base64,'+Buffer.from(reminderSource).toString('base64'));
assert.equal(models.zonedToISO('2026-10-07T08:00','Europe/Berlin'),'2026-10-07T06:00:00.000Z');
assert.equal(models.zonedToISO('2026-12-07T08:00','Europe/Berlin'),'2026-12-07T07:00:00.000Z');
assert.equal(models.zonedToISO('2026-10-07T08:00','Europe/Kyiv'),'2026-10-07T05:00:00.000Z');
assert.throws(()=>models.zonedToISO('2026-03-29T02:30','Europe/Berlin'));
for(const value of ['2026-10-07T08:00','2026-10-25T01:30','2026-10-25T03:30','2026-12-07T08:00'])assert.equal(models.localDateInput(models.zonedToISO(value,'Europe/Berlin'),'Europe/Berlin'),value);
const now=new Date('2026-10-07T06:00:00Z');
const task={id:'task1',title:'Перевірити код',due_at:'2026-10-07T06:30:00Z',reminder_version:0};
assert.equal(reminders.needsDeadline(task,now),true);
assert.equal(reminders.needsDeadline({...task,due_at:'2026-10-07T06:30:01Z'},now),false);
assert.equal(reminders.needsDeadline({...task,due_at:'2026-10-07T06:00:00Z'},now),false);
assert.equal(reminders.localTime(now,'Europe/Berlin'),'08:00');
assert.equal(reminders.localTime(new Date('2026-12-07T07:00:00Z'),'Europe/Berlin'),'08:00');
assert.notEqual(reminders.deadlineJobKey(task),reminders.deadlineJobKey({...task,reminder_version:1}));
assert.ok(reminders.morningText([task],now,'Europe/Berlin').includes('Перевірити код'));
console.log('Domain checks passed: timezone/DST, deadline boundary, morning time and reminder versions.');
