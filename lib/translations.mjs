/** @param {unknown} value @returns {'de'|'en'|'uk'} */
export function languageValue(value) { return value === 'de' || value === 'en' ? value : 'uk'; }
/** @param {'de'|'en'|'uk'} language @param {string} key @param {Record<string,string|number>} [params] */
export function translate(language, key, params = {}) {
  const text = language === 'uk' ? key : messages[key]?.[language] ?? key;
  return text.replace(/\{(\w+)\}/g, (match, name) => Object.hasOwn(params, name) ? String(params[name]) : match);
}
